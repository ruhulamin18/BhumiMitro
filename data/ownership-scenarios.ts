export const DEMO_SCENARIOS: OwnershipScenario[] = [
  SCENARIO_A,
  SCENARIO_B,
  SCENARIO_C,
  SCENARIO_D,
  SCENARIO_E,
];

/**
 * Returns scenario by key or code.
 */
export function getScenarioByKeyOrCode(keyOrCode: string): OwnershipScenario | null {
  if (!keyOrCode) return null;
  const clean = keyOrCode.trim().toLowerCase();

  const found = DEMO_SCENARIOS.find(
    (s) =>
      s.key.toLowerCase() === clean ||
      s.code.toLowerCase() === clean ||
      s.id.toLowerCase() === clean
  );

  if (found) return found;

  // Aliases and mappings from existing BM-DEMO ids to scenarios
  if (clean.includes('demo-001') || clean.includes('scenario-a') || clean === 'a') return SCENARIO_A;
  if (clean.includes('demo-002') || clean.includes('demo-003') || clean.includes('scenario-b') || clean === 'b') return SCENARIO_B;
  if (clean.includes('demo-005') || clean.includes('scenario-c') || clean === 'c') return SCENARIO_C;
  if (clean.includes('demo-010') || clean.includes('demo-012') || clean.includes('scenario-d') || clean === 'd') return SCENARIO_D;
  if (clean.includes('demo-017') || clean.includes('demo-018') || clean.includes('demo-020') || clean.includes('scenario-e') || clean === 'e') return SCENARIO_E;

  return null;
}
